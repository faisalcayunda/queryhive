      CONCAT('row-', n, '-c10'), CONCAT('row-', n, '-c11'), CONCAT('row-', n, '-c12'),
      CONCAT('row-', n, '-c13'), CONCAT('row-', n, '-c14'), CONCAT('row-', n, '-c15'),
      CONCAT('row-', n, '-c16'), CONCAT('row-', n, '-c17'), CONCAT('row-', n, '-c18'),
      CONCAT('row-', n, '-c19'), CONCAT('row-', n, '-c20'), CONCAT('row-', n, '-c21'),
      CONCAT('row-', n, '-c22'), CONCAT('row-', n, '-c23'), CONCAT('row-', n, '-c24'),
      CONCAT('row-', n, '-c25'), CONCAT('row-', n, '-c26'), CONCAT('row-', n, '-c27'),
      CONCAT('row-', n, '-c28'), CONCAT('row-', n, '-c29'));
    SET n = n + 1;
  END WHILE;
END //
DELIMITER ;
SET autocommit = 0;
