-- A MySQL-5.7-compatible stand-in for `seed-mysql.sql`, for this reason only:
-- the generated fixture loads `wide_500k` with a recursive CTE, which needs
-- MySQL 8.0, so on 5.7 *no* table gets created and every test fails for want of
-- a fixture. That failure is about the fixture, not about the driver, and this
-- file removes the confound. It is derived from seed-mysql.sql (lines 1-34 and
-- 80-123, unchanged) with the CTE replaced by a loop.
--
-- Two deliberate differences from the real fixture, so the numbers it produces
-- are read with that in mind:
--   * 20,000 rows instead of 500,000. The streaming test reads the first 1,000,
--     so that is enough; row-by-row insertion under amd64 emulation is slow.
--   * no ANALYZE TABLE, so `information_schema.TABLES.TABLE_ROWS` is left empty.
--     The test that reads it treats a missing count as "not known" already.
-- generated by deploy/dev/make_seed.py -- do not edit by hand
